"""Пересчёт долей офферов в потоке: порядок долей = порядок офферов в таблице.

При изменении состава потока закреплённые (pinned) офферы сохраняют свою долю,
а остаток до 100 делится между остальными — см. redistribute(n, total).
"""


def redistribute(n: int, total: int = 100) -> list[int]:
    """n долей с суммой total: base = total // n, первые total % n элементов получают base + 1.

    Примеры: 3 -> [34, 33, 33], 4 -> [25, 25, 25, 25], 5 -> [20, 20, 20, 20, 20].
    Остаток после закреплённых долей: redistribute(2, 75) -> [38, 37].
    """
    if n <= 0:
        raise ValueError("Число офферов должно быть положительным")
    if total < 0:
        raise ValueError("Распределяемая сумма не может быть отрицательной")
    base, extra = divmod(total, n)
    return [base + 1] * extra + [base] * (n - extra)
