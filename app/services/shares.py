"""Пересчёт долей офферов в потоке: сумма всегда 100, порядок долей = порядок офферов в таблице."""


def redistribute(n: int) -> list[int]:
    """n долей с суммой 100: base = 100 // n, первые 100 % n элементов получают base + 1.

    Примеры: 3 -> [34, 33, 33], 4 -> [25, 25, 25, 25], 5 -> [20, 20, 20, 20, 20].
    """
    if n <= 0:
        raise ValueError("Число офферов должно быть положительным")
    base, extra = divmod(100, n)
    return [base + 1] * extra + [base] * (n - extra)
